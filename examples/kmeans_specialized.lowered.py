@cake.raw_kernel()
def kmeans_assign(k, X: LM.tma3d, C: LM.tma3d, CN: LM.gmem, OUT: LM.gmem):
    B, N, K, D = k.dims('B', 'N', 'K', 'D')
    MBAR_BASE = k.align((0 + (((128 * D) * 2) + (2 * ((128 * D) * 2)))), 8)
    k.launch(grid=(k.cdiv(N, 128), B, 1), warps=6, smem_bytes=k.align((((((MBAR_BASE + 8) + 16) + 16) + 16) + 16), 128), tmem_cols=256)
    bx, by, bz = k.block_idx(0), k.block_idx(1), k.block_idx(2)
    # mbarriers: x_full@0x18000, c_full[0]@0x18008, c_full[1]@0x18010, c_free[0]@0x18018, c_free[1]@0x18020, acc_full[0]@0x18028, acc_full[1]@0x18030, acc_free[0]@0x18038, acc_free[1]@0x18040
    with k.prologue():
        k.mbar_init((MBAR_BASE + 0), 1)
        k.mbar_init(((MBAR_BASE + 8) + 0), 1)
        k.mbar_init(((MBAR_BASE + 8) + 8), 1)
        k.mbar_init((((MBAR_BASE + 8) + 16) + 0), 1)
        k.mbar_init((((MBAR_BASE + 8) + 16) + 8), 1)
        k.mbar_init(((((MBAR_BASE + 8) + 16) + 16) + 0), 1)
        k.mbar_init(((((MBAR_BASE + 8) + 16) + 16) + 8), 1)
        k.mbar_init((((((MBAR_BASE + 8) + 16) + 16) + 16) + 0), 1)
        k.mbar_init((((((MBAR_BASE + 8) + 16) + 16) + 16) + 8), 1)
    with k.warps([0], "load"):
        k.set("ph_c_free", 3)
        k.mbar_expect_tx((MBAR_BASE + 0), (0 + ((128 * D) * 2)))
        k.tma_load((0 + (0 * ((128 * D) * 2))), X, (by, (bx * 128), 0,), (128, D), "128B", (MBAR_BASE + 0))
        for j in k.range(0, k.cdiv(K, 128), 1):
            k.mbar_wait((((MBAR_BASE + 8) + 16) + ((j % 2) * 8)), ((k.reg("ph_c_free") >> (j % 2)) & 1))
            k.set("ph_c_free", (k.reg("ph_c_free") ^ (1 << (j % 2))))
            k.mbar_expect_tx(((MBAR_BASE + 8) + ((j % 2) * 8)), (0 + ((128 * D) * 2)))
            k.tma_load(((0 + ((128 * D) * 2)) + ((j % 2) * ((128 * D) * 2))), C, (by, (j * 128), 0,), (128, D), "128B", ((MBAR_BASE + 8) + ((j % 2) * 8)))
    with k.warps([1], "mma"):
        k.set("ph_x_full", 0)
        k.set("ph_c_full", 0)
        k.set("ph_acc_free", 3)
        k.mbar_wait((MBAR_BASE + 0), ((k.reg("ph_x_full") >> 0) & 1))
        k.set("ph_x_full", (k.reg("ph_x_full") ^ 1))
        for j_1 in k.range(0, k.cdiv(K, 128), 1):
            k.mbar_wait(((MBAR_BASE + 8) + ((j_1 % 2) * 8)), ((k.reg("ph_c_full") >> (j_1 % 2)) & 1))
            k.set("ph_c_full", (k.reg("ph_c_full") ^ (1 << (j_1 % 2))))
            k.mbar_wait((((((MBAR_BASE + 8) + 16) + 16) + 16) + ((j_1 % 2) * 8)), ((k.reg("ph_acc_free") >> (j_1 % 2)) & 1))
            k.set("ph_acc_free", (k.reg("ph_acc_free") ^ (1 << (j_1 % 2))))
            k.umma(((j_1 % 2) * 128), k.smem_desc((0 + (0 * ((128 * D) * 2))), 128, D, k.bf16, "128B"), k.smem_desc(((0 + ((128 * D) * 2)) + ((j_1 % 2) * ((128 * D) * 2))), 128, D, k.bf16, "128B"), 128, 128, D, False, "K")
            k.umma_commit((((MBAR_BASE + 8) + 16) + ((j_1 % 2) * 8)))
            k.umma_commit(((((MBAR_BASE + 8) + 16) + 16) + ((j_1 % 2) * 8)))
    with k.warps([2, 3, 4, 5], "epi"):
        best = k.regs((128,), k.f32, name="best")
        arg = k.regs((128,), k.i32, name="arg")
        s = k.regs((128, 128), k.f32, name="s")
        cn = k.regs((128,), k.f32, name="cn")
        k.set("ph_acc_full", 0)
        k.fill(best, float('inf'))
        k.fill(arg, 0)
        for j_2 in k.range(0, k.cdiv(K, 128), 1):
            k.ld_global(cn, CN, (by, (j_2 * 128),))
            k.mbar_wait(((((MBAR_BASE + 8) + 16) + 16) + ((j_2 % 2) * 8)), ((k.reg("ph_acc_full") >> (j_2 % 2)) & 1))
            k.set("ph_acc_full", (k.reg("ph_acc_full") ^ (1 << (j_2 % 2))))
            k.tmem_load(s, ((j_2 % 2) * 128), 128, 128)
            k.mbar_arrive((((((MBAR_BASE + 8) + 16) + 16) + 16) + ((j_2 % 2) * 8)))
            k.ewise(s, "fma", s, -2.0, cn.row())
            k.reduce(best, s, "argmin", idx=arg, index_offset=(j_2 * 128), valid=(K - (j_2 * 128)))
        k.st_global(OUT, (by, (bx * 128),), arg, valid=(N - (bx * 128)))
